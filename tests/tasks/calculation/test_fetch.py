def row(problem: str, answer: str = "12", **fields: object) -> dict[str, object]:
    """A source row of a valid word problem from a school collection, with `fields` given."""
    return {
        "problem": problem,
        "answer": answer,
        "problem_type": "Algebra",
        "question_type": "math-word-problem",
        "problem_is_valid": "Yes",
        "solution_is_valid": "Yes",
        "source": "cn_k12",
        "synthetic": False,
    } | fields


ROWS = [
    row("What is $3 \\times 4$?\r\n\n\n\nGive a number."),
    row("A train covers 60 km in 40 minutes. Find its speed in km/h.", "90", source="olympiads"),
    row("The ratio of $x$ to $y$ is $1:2$. Find $x/y$.", "\\frac{1}{2}", source="cn_contest"),
    row("Find the side of a square of area 2.", "\\sqrt{2}", problem_type="Geometry"),
    row("Which is larger, $2^{10}$ or $10^3$?", "proof", question_type="proof"),
    row("Pick the right option.", "B", question_type="MCQ"),
    row("Something unclear.", problem_is_valid="Incomplete"),
    row("Generated by a model.", synthetic=True, source="synthetic_math"),
    row("As shown in the figure, find the angle."),
    row("(I) Find $a$. (II) Find $b$."),
    row("x" * (fetch.MAX_PROBLEM_CHARS + 1)),
    row("Solve $x^2 = 4$.", "\\pm 2"),
    row("What is $3 \\times 4$?\n\n\nGive a number."),
]


def test_valid_word_problems_with_one_number_as_answer_are_sampled_by_hash(monkeypatch, tmp_path):
    problems, dropped = fetch.convert(ROWS)
    assert dropped == Counter(
        {
            "not a word problem": 2,
            "the problem or its solution is not marked valid": 1,
            "synthetic": 1,
            "it refers to a figure": 1,
            "it has several parts": 1,
            f"longer than {fetch.MAX_PROBLEM_CHARS} characters": 1,
            "the answer is not one number": 1,
            "it repeats an earlier problem": 1,
        }
    )
    assert [
        problem.task["problem"] for problem in problems if "3 \\times 4" in problem.task["problem"]
    ] == ["What is $3 \\times 4$?\n\nGive a number."]
    assert {problem.task["title"] for problem in problems} == {
        "An algebra problem",
        "A geometry problem",
    }
    assert Counter(problem.label for problem in problems) == {
        Difficulty.EASY: 2,
        Difficulty.HARD: 1,
        Difficulty.MEDIUM: 1,
    }

    monkeypatch.setattr(fetch, "POOL_SIZE", 2)
    sampled, dropped = fetch.convert(ROWS)
    assert dropped["outside the sample"] == 2
    assert fetch.convert(reversed(ROWS))[0] == sampled
    by_hash = sorted(problems, key=lambda problem: fetch.hashed(problem.name))
    assert {problem.name for problem in sampled} == {problem.name for problem in by_hash[:2]}


async def test_a_calculation_is_judged_by_its_answer_alone(tmp_path):
    problems, _ = fetch.convert(ROWS)
    bank.build(tmp_path, Trade.CALCULATION, CalculationTask, fetch.TERMS, fetch.Entry, problems, {})
    assert trade_of(tmp_path / "pool") is Trade.CALCULATION
    provider = CalculationProvider(tmp_path / "pool")
    [name] = [name for name, task in provider.bank.items() if task.answer == "\\sqrt{2}"]
    part = provider.part(name)
    assert part.specification.startswith("Find the side of a square of area 2.\n\n")
    assert "Answer: " in part.specification and "\\sqrt{2}" not in part.specification
    deliveries = {
        "The area is $s^2 = 2$, so $s = \\sqrt{2}$.\nAnswer: $\\sqrt{2}$": (True, 1.0, SAME),
        "Since s*s = 2:\nAnswer: √2": (True, 1.0, SAME),
        "Taking roots, the side is $\\boxed{\\sqrt 2}$.": (True, 1.0, SAME),
        "Roughly.\nAnswer: 1.414": (False, 0.0, DIFFERS),
        "Answer: 2": (False, 0.0, DIFFERS),
        "The side is the root of two.": (False, 0.0, MISSING),
    }
    for delivery, verdict in deliveries.items():
        assessment = await provider.assess(part, delivery)
        assert (assessment.passed, assessment.quality, assessment.feedback) == verdict
        assert not provider.special_cased(part, delivery)


def test_the_source_files_are_read_column_by_column(tmp_path):
    pyarrow = pytest.importorskip("pyarrow")
    parquet = pytest.importorskip("pyarrow.parquet")
    columns = {name: [value[name] for value in ROWS[:3]] for name in fetch.COLUMNS}
    table = pyarrow.table({**columns, "solution": ["..."] * 3})
    parquet.write_table(table, tmp_path / "train.parquet")
    assert list(fetch.records([tmp_path / "train.parquet"])) == ROWS[:3]
